/**
 * 线上消息的**编码**与**体积上限** —— 分帧已经交给 WebSocket 了。
 *
 * ## 这一版为什么不再有解码器
 *
 * 上一版的帧协议是 JSON-lines：`\n` 是帧边界，带字节的请求在帧后紧跟恰好 N 个原始字节，
 * 于是需要一台状态机（`FrameDecoder`）在字节流上找边界、进二进制阶段、收满再吐。
 *
 * 换成 WebSocket 之后这些东西都不见了：**每条消息自带边界**，是文本还是二进制由传输层
 * 告诉我们（`Wire.onText` / `Wire.onBinary`）。所以「切帧」这件事没有第二份实现，也不需要
 * 一份 —— 净减法。
 *
 * ## 文本不再带结尾 `\n`
 *
 * 边界只有 WebSocket 一个来源，再加一个 `\n` 就是两套约定（谁负责去掉它？）。于是编码退化成
 * 一句 `JSON.stringify`。
 *
 * ## 两个体积上限，各管一侧
 *
 *   · `MAX_PAYLOAD_BYTES`（64 MiB）—— **单条消息**的上限，交给 WebSocket 的 `maxPayload`：
 *     超了由传输层直接断连；
 *   · `MAX_TEXT_BYTES`（8 MiB）—— 文本消息的额外上限，在实现层卡。文本是一条能装多少
 *     JSON 的问题，与二进制（图片 / 附件）不是同一件事；二进制可以用满 64 MiB。
 *
 * 两档的结果一样：**断连，不先发错误响应**。没有可回应之物 —— 那条消息在体积上就没被
 * 收下（64 MiB 那档连一条完整的消息都没组装出来），而同一段内容重发一遍还是这么大，
 * 没有「改一次请求再试」的恢复路径。与「不是合法 JSON」不同：那一条回 `bad-frame`、不断连。
 *
 * 上一版那个 `frame-too-large` 码随之退场：超限这件事在 WS 层就已经结束了，本版永远不会
 * 发出它。
 */

/**
 * 单条消息的硬上限：64 MiB（交给 WebSocket 的 `maxPayload`）。
 *
 * 二进制帧可以用满它（粘贴一张大图），文本帧另有 {@link MAX_TEXT_BYTES}。
 */
export const MAX_PAYLOAD_BYTES = 64 * 1024 * 1024;

/**
 * 文本消息的实现层上限：8 MiB。
 *
 * 一条 8 MiB 的 JSON 已经远远超出本协议任何一条请求的形状（最大的结果也不是这个量级），
 * 超过它的只可能是对端搞错了。它的结果是**断连**（见文件头）：这种消息没有一条能给出的
 * 错误响应 —— 而对端能做的唯一修正是别发这么大的东西，它不需要一条错误提示才能知道。
 */
export const MAX_TEXT_BYTES = 8 * 1024 * 1024;

/**
 * 把一条消息编码成要写在 WS 上的文本。
 *
 * 没有结尾换行（见文件头）。参数叫 `frame` 而不是「一条消息」：它是「要被编码的那个线上
 * 对象」，与对话消息无关 —— 后者是具名类型（`Message`）。两个概念共用一个词，读代码的人
 * 会以为这里能递一条对话消息。
 */
export function encodeFrame(frame: unknown): string {
  return JSON.stringify(frame);
}
