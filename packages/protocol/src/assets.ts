/**
 * 资产清单线上契约 —— `asset.*`：一段工作区里「能被发现的能力」有哪些。
 *
 * ## 为什么单开一个命名空间（而不是塞进 `session.*` / `config.*`）
 *
 * 判据仍是那一句：**这个方法的作用对象是谁**。资产的作用对象既不是某一段会话（它描述的是
 * 「这个工作区/这台机器上装了什么」），也不是全局配置的某个字段（那些方法改的是
 * `config.json` / `agents/*.json` 里的值，资产**根本不在配置里** —— 它们是一堆目录和文件，
 * 由 SDK 的发现逻辑扫出来）。
 *
 * 更要紧的是**读写性质**：`config.*` / `agent.*` 是读写面，而 `asset.*` **只读**。
 * 混进配置命名空间，调用方会本能地以为「这里也能改」（改资产 = 改用户的文件系统，是另一件
 * 需要另外设计的事：权限、冲突、谁在跑）。命名空间分开，这条边界就是文件边界。
 *
 * 目前只有一条方法（`asset.list`）；以后出现 `asset.read`（读正文）/ `asset.install`，归这个文件。
 *
 * ## 为什么不引用 SDK 的类型
 *
 * 协议是线上契约，客户端不该为了一个枚举去装 SDK。
 * 这里的 `kind` / `scope` 是「客户端要能自己拼请求」的最小词汇表，所以写死；
 * 而资产**内容**（名字、描述）是发现的结果，形状由本文件定义 —— 它比 SDK 的
 * `SkillInfo` / `Tool` 窄得多（那几个携带正文、工具参数表、导入实例），客户端渲染一行列表
 * 用不上，也不该拿到。
 */

/**
 * 资产方法名（服务端注册与客户端调用共用同一份字面量）。
 *
 * 只读：**不做**增删改。资产是用户的文件系统（`~/.ai-zen/skills/`、
 * `<工作区>/.ai-zen/tools/` …），改它意味着替用户动他手写的文件，那是另一个动作
 * （也要另一套权限与冲突设计），不该藏在「列个清单」旁边。
 */
export const ASSET_METHODS = {
  /**
   * 列出某个工作区（或全局）的资产。
   *
   * 为什么需要它：客户端（TUI 的技能面板、桌面端的配置中心）要显示「有哪些 skill / 工具、
   * 来自哪一层」。而**发现规则在服务端**（扫哪些目录、同名谁优先、哪些文件不是工具）——
   * 客户端自己扫一遍就是第二套规则，两份迟早不一致（典型症状：Agent 实际能用 12 个 skill，
   * 面板上列了 9 个，用户以为坏了）。
   */
  list: "asset.list",
} as const;

/** 资产类别：目前只有技能与用户工具（内置工具、MCP 服务器、子 Agent 不在这里） */
export type AssetKind = "skill" | "tool";

/**
 * 资产来自哪一层。
 *
 * 定义只有一句：**挂在工作区路径下的就是 `project`，其余是 `global`**。
 * 同一个名字在两层都有时，`project` 覆盖 `global`（与能力发现的优先级同一套规则），
 * 所以清单里一个名字只会出现一次，`source` 说明它是被哪一层供上的。
 */
export type AssetScope = "global" | "project";

/**
 * 清单里的一条。
 *
 * 不带正文 / 不带参数表：列表只需要「一行怎么显示」。要正文的调用方（今天没有）应该走
 * 另一条方法 —— 把几 KB 的 SKILL.md 塞进列表，会让一次刷新变成几 MB 的传输。
 */
export interface AssetSummary {
  /**
   * 稳定标识：skill 是目录名、工具是文件名（不含扩展名）。
   *
   * 它就是能力发现用的那个键（`load_skill` 的候选名、工具名去重的依据），不是展示名 ——
   * 展示用 `name`。
   */
  id: string;
  /** 展示名：skill 取 `SKILL.md` 的 `name`，工具取 `function.name` */
  name: string;
  /** 说明；为空就不带这个字段（客户端不必区分「空字符串」与「没有描述」） */
  description?: string;
  /** 来自哪一层（见 `AssetScope`） */
  source: AssetScope;
  /**
   * 服务端磁盘上的位置。
   *
   * skill 是**目录**（`<…>/skills/<id>`，`SKILL.md` 在它里面），工具是**文件**
   * （`<…>/tools/<name>.js`）：这两类资产的单位本来就不一样（一个技能是多文件的一整个目录）。
   * 客户端拿它显示详情、或在服务端同机时直接打开；两机部署时它只是一条信息。
   */
  path: string;
}

export interface AssetListParams {
  /** 列哪一类 */
  kind: AssetKind;
  /**
   * 只看哪一层；**缺省两层都列**（每条自带 `source`）。
   *
   * `project` 时 `workspaceId` 必填：项目级资产挂在工作区路径上，没有工作区就无从知道
   * 挂在哪 —— 那不是「空清单」，是调用方漏了参数（`bad-params`）。
   *
   * 缺省（两层都列）但没给 `workspaceId` 时只会有 `global` 条目：服务端不会替客户端猜
   * 「你说的项目是哪个」。（会话层有「服务端默认工作区」那套缺省，但那是**会话**跑在哪，
   * 与「列哪一层资产」不是同一个问题。）
   */
  scope?: AssetScope;
  /** 哪个工作区（`scope: "project"` 必填；缺省两层都列时给了它就包含项目层） */
  workspaceId?: string;
}

export interface AssetListResult {
  assets: AssetSummary[];
}
