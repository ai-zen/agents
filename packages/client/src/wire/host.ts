/**
 * 「这个地址是不是本机回环」—— 服务端与客户端各有一份**逐字相同**的实现（本文件是其中一份）。
 *
 * ## 为什么这件事必须只有一个答案
 *
 * 两端都在用它判断同一件事，但关心的是不同后果：
 *
 *   - **服务端**（`Daemon.start()`）：未鉴权的端口一旦能被非本机访问，等于把 `exec`
 *     送给整个局域网，所以只肯绑回环地址；
 *   - **客户端**（`local-host.ts`）：确认「服务端就在这台机器上」之后，才把**自己的** cwd
 *     当作工作区递上去（两机部署时那个目录在服务端根本不存在）。
 *
 * ## 为什么是两份一样的实现，而不是共享一个导出
 *
 * 运行期件在两端不共享代码（共享的只有 `@ai-zen/agents-server/protocol` 那一组类型）：
 * 判据只有三十来行，各编一份比让客户端为了一次地址判断去装整套服务端实现便宜得多。
 * 代价记在明处 —— 两份必须逐字一致，改一边就得同时改另一边。
 *
 * 两端各写**各的**判据是行不通的：服务端若用精确集合 `{127.0.0.1, ::1, localhost}`（于是
 * `127.0.0.2` 会被拒绝启动），客户端若用 `/^127\./`（于是会把 `127.0.0.1.example` 当本机），
 * 同一个概念就会有两个答案。
 *
 * ## 为什么取宽的那一侧
 *
 * `127.0.0.0/8` 整段都是本机回环（RFC 1122），不只是 `127.0.0.1`。按整段判定既不减弱
 * 服务端的安全性（绑在这段里的任何地址都只有本机能连），又不会在「某个环境把
 * `--host` 写成 `127.0.0.2`」时给出一个看起来像 bug 的拒绝。
 */
/**
 * `127.0.0.0/8` 的整段：四段点分十进制，首段 127。
 *
 * 不能用 `/^127\./`：那样 `127.0.0.1.example` 也会被当成回环 —— 一个前缀匹配的误报
 * 在服务端是「把一个域名当成本机绑上去」，在客户端是「把会话开在别人机器上」。
 */
const IPV4_LOOPBACK = /^127(?:\.\d{1,3}){3}$/;

export function isLoopbackHost(host: string): boolean {
  const value = host
    .trim()
    .toLowerCase()
    // IPv6 字面量可以带方括号（`[::1]`），去掉再比
    .replace(/^\[|\]$/g, "");
  return value === "localhost" || value === "::1" || IPV4_LOOPBACK.test(value);
}
