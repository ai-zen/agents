/**
 * 线上消息的**编码**与**体积上限** —— 分帧已经交给 WebSocket 了（客户端这一侧的那一份）。
 *
 * ## 这一版为什么不再有解码器
 *
 * 上一版的帧协议是 JSON-lines：`\n` 是帧边界，带字节的请求在帧后紧跟恰好 N 个原始字节，于是
 * 需要一台状态机（`FrameDecoder`）在字节流上找边界、进二进制阶段、收满再吐。客户端的这份是
 * 服务端的**平行副本**（逐字相同，改一边就得改另一边）。
 *
 * 换成 WebSocket 之后这些东西都不见了：**每条消息自带边界**，是文本还是二进制由传输层告诉
 * 我们（浏览器/Node 内建 `WebSocket` 的 `message` 事件里 `typeof data`/`Blob`/`ArrayBuffer`
 * 已经分了类）。所以客户端这边也不再切帧 —— 净减法。
 *
 * 与服务端那份逐字同形的部分只有三样：{@link encodeFrame} 与两个上限。差异只在**谁在乎
 * 哪个上限**：服务端要在入站卡 8 MiB 的文本，客户端只发不收，两道闸门都在对端，这里留着
 * 两个数只是为了让「上限是多少」只有一个来源（诊断与将来的入站检查都要读它）。
 *
 * ## 文本不再带结尾 `\n`
 *
 * 边界只有 WebSocket 一个来源，再加一个 `\n` 就是两套约定（谁负责去掉它？）。于是编码退化成
 * 一句 `JSON.stringify`。
 *
 * ## 两个体积上限，各管一侧
 *
 *   · `MAX_PAYLOAD_BYTES`（64 MiB）—— **单条消息**的上限，对端是 WebSocket 的 `maxPayload`：
 *     超了由传输层直接断连；
 *   · `MAX_TEXT_BYTES`（8 MiB）—— 文本消息的额外上限，服务端在实现层卡。文本是一条能装多少
 *     JSON 的问题，与二进制（图片 / 附件）不是同一件事；二进制可以用满 64 MiB。
 *
 * 上一版那个 `frame-too-large` 码随之退场（A19）：超限这件事在 WS 层就已经结束了，本版永远
 * 不会发出也不会收到它。
 */

/**
 * 单条消息的硬上限：64 MiB（服务端交给 WebSocket 的 `maxPayload`）。
 *
 * 二进制消息可以用满它（粘贴一张大图），文本消息另有 {@link MAX_TEXT_BYTES}。
 */
export const MAX_PAYLOAD_BYTES = 64 * 1024 * 1024;

/**
 * 文本消息的实现层上限：8 MiB（服务端卡；客户端这一侧只发文本请求，远不到这个量级）。
 *
 * 一条 8 MiB 的 JSON 已经远远超出本协议任何一条请求的形状（最大的结果也不是这个量级），
 * 超过它的只可能是对端搞错了。
 */
export const MAX_TEXT_BYTES = 8 * 1024 * 1024;

/**
 * 把一条消息编码成要写在 WS 上的文本。
 *
 * 没有结尾换行（见文件头）。参数叫 `frame` 而不是「一条消息」：它是「要被编码的那个线上
 * 对象」，与对话消息无关 —— 后者是具名类型（`Message`）。两个概念共用一个词，读代码的人
 * 会以为这里能递一条对话消息。
 *
 * 只管文本消息：带字节的请求由调用方在 `encodeFrame()` 之后再发**一条二进制消息**（前 4
 * 字节是请求 `id`，见 `wire/messages.ts` 的 `REQUEST_ID_BYTES`）。
 */
export function encodeFrame(frame: unknown): string {
  return JSON.stringify(frame);
}
